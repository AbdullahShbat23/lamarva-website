"""Download the site's web fonts once and serve them from the site itself (no requests to Google).

    python tools/fetch-fonts.py

Writes assets/fonts/*.woff2 and assets/css/fonts.css. Only the character sets the site uses are kept:
Latin (English) for Playfair Display and Inter, Arabic + Latin for El Messiri and IBM Plex Sans Arabic.
All four fonts are under the SIL Open Font License, which allows self-hosting.
"""
import os
import re
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSS_URL = ("https://fonts.googleapis.com/css2?family=Playfair+Display:wght@400;500;600"
           "&family=Inter:wght@400;500;600&family=El+Messiri:wght@400;500;600"
           "&family=IBM+Plex+Sans+Arabic:wght@400;500;600&display=swap")
# A current browser identity makes Google return compact .woff2 files.
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
KEEP = {"latin", "latin-ext", "arabic"}


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


css = get(CSS_URL).decode("utf-8")
blocks = re.findall(r"/\* ([a-z-]+) \*/\s*(@font-face\s*\{[^}]*\})", css)
out_dir = os.path.join(ROOT, "assets", "fonts")
os.makedirs(out_dir, exist_ok=True)

seen = {}
rules = []
for subset, block in blocks:
    if subset not in KEEP:
        continue
    family = re.search(r"font-family:\s*'([^']+)'", block).group(1)
    weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
    url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
    if url not in seen:  # Google serves one variable file for several weights
        name = "%s-%s.woff2" % (family.lower().replace(" ", "-"), subset)
        if name in seen.values():
            name = "%s-%s-%s.woff2" % (family.lower().replace(" ", "-"), subset, weight)
        with open(os.path.join(out_dir, name), "wb") as fh:
            fh.write(get(url))
        seen[url] = name
    rules.append("/* %s %s %s */\n%s" % (family, weight, subset, block.replace(url, "../fonts/" + seen[url])))

with open(os.path.join(ROOT, "assets", "css", "fonts.css"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("/* Self-hosted web fonts (SIL Open Font License). Generated by tools/fetch-fonts.py. */\n")
    fh.write("\n".join(rules) + "\n")

total = sum(os.path.getsize(os.path.join(out_dir, n)) for n in set(seen.values()))
print("%d @font-face rules, %d font files, %d KB" % (len(rules), len(set(seen.values())), total // 1024))
